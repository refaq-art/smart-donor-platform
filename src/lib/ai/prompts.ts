export function buildUserPrompt(action: AIActionType, context: Record<string, string | undefined>): string {
  const ctxLines = Object.entries(context)
    .filter(([, v]) => v && v.trim())
    .map(([k, v]) => `${k}: ${v}`)
    .join("\n");

  const instructions: Record<AIActionType, string> = {
    draft_executive_summary:
      "بناءً على المعلومات التالية عن المشروع، اكتب ملخصًا تنفيذيًا احترافيًا (فقرة إلى فقرتين) لطلب منحة.",
    improve_problem_statement: "أعد صياغة وصف المشكلة التالي بشكل أكثر وضوحًا وإقناعًا للجهة المانحة.",
    suggest_objectives:
      "اقترح 3-5 أهداف تفصيلية قابلة للقياس (SMART) بناءً على المشكلة والهدف العام التاليين.",
    suggest_activities: "اقترح قائمة أنشطة تنفيذية منطقية تحقق الأهداف التالية.",
    suggest_outputs_outcomes: "بناءً على الأنشطة التالية، اقترح مخرجات مباشرة ونتائج متوقعة على مستوى الأثر.",
    suggest_kpis: "اقترح مؤشرات أداء (KPIs) قابلة للقياس لمتابعة النتائج التالية.",
    check_consistency:
      "راجع الترابط المنطقي بين المشكلة والأهداف والأنشطة والنتائج التالية، واذكر أي تكرار أو تناقض أو فجوة منطقية.",
    rewrite_formal: "أعد صياغة النص التالي بأسلوب رسمي مؤسسي مناسب لمخاطبة الجهات المانحة.",
    simplify_text: "بسّط النص التالي وقلل من طوله دون فقد المعنى الأساسي.",
    summarize_opportunity: "لخّص شروط ومتطلبات فرصة التمويل التالية في نقاط واضحة.",
    compare_project_opportunity:
      "قارن بين بيانات المشروع وشروط فرصة التمويل التاليين، وبيّن مدى الملاءمة والفجوات إن وجدت.",
    missing_data_checklist:
      "راجع بيانات طلب المنحة التالية وأنشئ قائمة بالحقول أو البيانات الناقصة أو غير الواضحة.",
    readiness_assessment:
      "قيّم جاهزية طلب المنحة التالي للإرسال إلى الجهة المانحة، واذكر نقاط القوة ونقاط تحتاج تحسينًا.",
    clarifying_questions: "بناءً على المعلومات الناقصة التالية، اقترح أسئلة توضيحية دقيقة للمستخدم.",
    extract_donor_lead: "استخلص بيانات مانح محتمل من نتيجة بحث ويب.",
    custom: "ساعد المستخدم في الطلب التالي.",
  };

  if (action === "extract_donor_lead") {
    return `لديك نتيجة بحث واحدة من الويب (عنوان، رابط، ومقتطف نصي)، وقائمة بمشاريع الجمعية النشطة حاليًا. مهمتك:
1. حدد هل تتحدث هذه النتيجة فعليًا عن جهة مانحة محتملة أو فرصة تمويل (وليس عن موضوع آخر غير ذي صلة).
2. إن كانت ذات صلة، استخلص اسم الجهة المانحة ومجال دعمها ومدينتها/نطاقها الجغرافي إن ذُكر — من المقتطف فقط، ولا تخترع أي تفاصيل غير مذكورة فيه.
3. من قائمة المشاريع المزوّدة، اختر المشروع الأنسب لرفعه لهذه الجهة إن وُجد تطابق واضح في المجال، واذكر سببًا مختصرًا؛ وإلا اجعله null.
4. اكتب ملاحظة قصيرة (جملة واحدة) عن أي توجه أو نمط عام تلاحظه في هذه النتيجة (مثل نوع الدعم الرائج، أو شرط متكرر).

أجب **حصرًا** بكائن JSON صالح بلا أي نص إضافي قبله أو بعده، بالضبط بهذا الشكل:
{"isDonorRelevant": true|false, "donorName": "..."|null, "about": "..."|null, "sector": "..."|null, "city": "..."|null, "matchProjectId": "..."|null, "matchReason": "..."|null, "trendNote": "..."|null}

المعلومات المتوفرة:
${ctxLines || "(لا توجد معلومات كافية مزوّدة)"}

تذكير: لا تختلق أي معلومة غير موجودة صراحة في المقتطف أعلاه. إن لم يكن المقتطف كافيًا لتحديد اسم الجهة بثقة، اجعل isDonorRelevant بقيمة false.`;
  }

  return `${instructions[action]}\n\nالمعلومات المتوفرة:\n${ctxLines || "(لا توجد معلومات كافية مزوّدة)"}\n\nالتزم بعدم اختلاق أي معلومة غير مذكورة أعلاه.`;
}
