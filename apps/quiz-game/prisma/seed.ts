async function main() {
  console.log('🌱 بدء زراعة البيانات...');

  // -------- التصنيفات --------
  const categoryByKey = new Map<string, string>();
  for (const c of CATEGORY_SEED) {
    const category = await prisma.category.upsert({
      where: { key: c.key },
      update: { nameAr: c.nameAr, icon: c.icon, colorHex: c.colorHex },
      create: { key: c.key, nameAr: c.nameAr, icon: c.icon, colorHex: c.colorHex },
    });
    categoryByKey.set(c.key, category.id);
  }
  console.log(`✅ ${categoryByKey.size} تصنيفًا`);

  // -------- الإنجازات --------
  for (const a of ACHIEVEMENT_DEFINITIONS) {
    await prisma.achievement.upsert({
      where: { key: a.key },
      update: { nameAr: a.nameAr, descriptionAr: a.descriptionAr, icon: a.icon, criteria: a.criteria },
      create: { key: a.key, nameAr: a.nameAr, descriptionAr: a.descriptionAr, icon: a.icon, criteria: a.criteria },
    });
  }
  console.log(`✅ ${ACHIEVEMENT_DEFINITIONS.length} إنجازًا`);

  // -------- حساب المسؤول --------
  const adminEmail = 'admin@quiz.local';
  const existingAdmin = await prisma.user.findUnique({ where: { email: adminEmail } });
  if (!existingAdmin) {
    const passwordHash = await bcrypt.hash('Admin@12345', 10);
    await prisma.user.create({
      data: {
        email: adminEmail,
        passwordHash,
        role: 'ADMIN',
        player: {
          create: { isGuest: false, displayName: 'مدير المنصة', avatarEmoji: '🛡️', avatarColor: '#ffb020' },
        },
      },
    });
    console.log(`✅ حساب مسؤول: ${adminEmail} / Admin@12345`);
  }

  // -------- تنظيف الأسئلة المكرّرة (بقايا من زراعة سابقة قبل إضافة الحماية) --------
  // نحذف فقط النسخ المكررة التي لم تُستخدم في أي جولة لعب فعلية، حفاظًا على سجل المباريات القديمة.
  const dupGroups = await prisma.question.groupBy({
    by: ['categoryId', 'type', 'textAr'],
    _count: { id: true },
    having: { id: { _count: { gt: 1 } } },
  });
  let removedDuplicates = 0;
  for (const g of dupGroups) {
    const dups = await prisma.question.findMany({
      where: { categoryId: g.categoryId, type: g.type, textAr: g.textAr },
      include: { _count: { select: { rounds: true } } },
      orderBy: { createdAt: 'asc' },
    });
    const withRounds = dups.filter((d) => d._count.rounds > 0);
    const keepId = (withRounds[0] ?? dups[0]).id;
    const toDeleteIds = dups.filter((d) => d.id !== keepId && d._count.rounds === 0).map((d) => d.id);
    if (toDeleteIds.length > 0) {
      await prisma.question.deleteMany({ where: { id: { in: toDeleteIds } } });
      removedDuplicates += toDeleteIds.length;
    }
  }
  if (removedDuplicates > 0) {
    console.log(`🧹 أُزيل ${removedDuplicates} سؤالًا مكررًا`);
  }

  // -------- الأسئلة --------
  // نزرع فقط الأسئلة غير الموجودة مسبقًا (بالمطابقة على التصنيف + النص + النوع)
  // بدل تخطي الزراعة بالكامل عند وجود أي سؤال — هذا يسمح بإضافة أسئلة جديدة إلى
  // QUESTIONS لاحقًا وزرعها تلقائيًا في كل نشر، دون المساس بأسئلة عدّلها المسؤول
  // يدويًا أو تكرار زرع ما هو موجود بالفعل.
  const existingQuestions = await prisma.question.findMany({ select: { categoryId: true, type: true, textAr: true } });
  const existingKeys = new Set(existingQuestions.map((q) => `${q.categoryId}::${q.type}::${q.textAr}`));

  let inserted = 0;
  let skipped = 0;
  for (const q of QUESTIONS) {
    const categoryId = categoryByKey.get(q.categoryKey);
    if (!categoryId) {
      console.warn(`⚠️ تصنيف غير معروف: ${q.categoryKey}`);
      continue;
    }

    const key = `${categoryId}::${q.type}::${q.textAr}`;
    if (existingKeys.has(key)) {
      skipped++;
      continue;
    }

    await prisma.question.create({
      data: {
        categoryId,
        type: q.type,
        difficulty: q.difficulty,
        textAr: q.textAr,
        imageUrl: q.imageUrl ?? null,
        explanationAr: q.explanationAr ?? null,
        timeLimitSeconds: TIME_LIMIT_BY_DIFFICULTY[q.difficulty],
        basePoints: BASE_POINTS_BY_DIFFICULTY[q.difficulty],
        status: 'ACTIVE',
        source: 'MANUAL',
        answers: {
          create: q.answers.map((a) => ({
            textAr: a.textAr,
            imageUrl: a.imageUrl ?? null,
            isCorrect: a.isCorrect,
            orderIndex: a.orderIndex ?? null,
          })),
        },
      },
    });
    existingKeys.add(key);
    inserted++;
  }
  console.log(`✅ ${inserted} سؤالًا جديدًا${skipped > 0 ? ` (تخطي ${skipped} موجود مسبقًا)` : ''}`);

  console.log('🎉 اكتملت زراعة البيانات بنجاح!');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
